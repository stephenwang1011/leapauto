const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const script = fs.readFileSync(path.join(__dirname, '../../main/assets/night-background.js'), 'utf8');
const material = { fragmentShader: 'void main(void) { gl_FragColor = vec4(1.0); }', uniforms: {} };
const car = { material: { fragmentShader: 'untouched' } };
const renderer = { toneMappingExposure: 1 };
const frames = [];
const window = { viewer: { frameState: { skyBox: { material } }, car, renderer, setFPS: (...args) => frames.push(args) } };
vm.runInNewContext(script, { window });
assert.equal(window.leapSetNightBackground(0.3, 0), true);
const patched = material.fragmentShader;
assert.match(patched, /void leapBackgroundMain\(\)/);
assert.equal(material.uniforms.leapBackgroundGain.value, 0.3);
material.needsUpdate = false;
assert.equal(window.leapSetNightBackground(1.5, 0.5), true);
assert.equal(material.fragmentShader, patched);
assert.equal(material.needsUpdate, false);
assert.equal(material.uniforms.leapBackgroundLift.value, 0.5);
assert.equal(car.material.fragmentShader, 'untouched');
assert.equal(renderer.toneMappingExposure, 1);
assert.deepEqual(frames[0], [30, 80, 'night_background']);
const second = { fragmentShader: 'precision highp float;\nvoid main () { gl_FragColor = vec4(.5); }', uniforms: {} };
window.viewer.frameState.skyBox.material = [material, second];
assert.equal(window.leapSetNightBackground(1, 0), true);
assert.equal(material.uniforms.leapBackgroundGain.value, 1);
assert.equal(material.uniforms.leapBackgroundLift.value, 0);
assert.equal(second.uniforms.leapBackgroundGain.value, 1);
assert.ok(second.fragmentShader.indexOf('precision highp float') < second.fragmentShader.indexOf('uniform float leapBackgroundGain'));
window.viewer.frameState.skyBox.material = { fragmentShader: 'unsupported', uniforms: {} };
assert.equal(window.leapSetNightBackground(1, 0), false);
window.viewer.frameState.skyBox = null;
assert.equal(window.leapSetNightBackground(1, 0), false);
console.log('night-background: uniform updates, one-time shader patch, isolation and unsupported fallback passed');
